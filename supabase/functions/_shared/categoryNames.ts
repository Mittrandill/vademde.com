export function categoryNameVariants(name: string): string[] {
  const normalized = name.trim().toLocaleLowerCase('tr-TR');
  const entry = Object.entries(CATEGORY_NAMES).find(([tr, en]) =>
    tr.toLocaleLowerCase('tr-TR') === normalized || en.toLocaleLowerCase('tr-TR') === normalized);
  return entry ? [name, ...entry] : [name];
}
